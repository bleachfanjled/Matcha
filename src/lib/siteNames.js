const capitalize = (s) => s ? s.charAt(0).toUpperCase() + s.slice(1) : s;

// Returns a clean brand name for a URL: known-site map first, then a
// capitalized second-level domain for unknown hosts.
export function siteNameFor(url) {
  let host;
  try { host = new URL(url).hostname.toLowerCase().replace(/^www\./, ''); } catch { return url; }
  if (SITE_NAMES[host]) return SITE_NAMES[host];
  // Try subdomain match (e.g., mail.google.com → Google)
  const parts = host.split('.');
  for (let i = 0; i < parts.length - 1; i++) {
    const sub = parts.slice(i).join('.');
    if (SITE_NAMES[sub]) return SITE_NAMES[sub];
  }
  // Fall back to the second-level domain, capitalized
  const sld = parts.length >= 2 ? parts[parts.length - 2] : parts[0];
  return capitalize(sld);
}